#[derive(Clone, Copy, PartialEq, Debug)]
enum Mode {
    Lobby = 0,
    Countdown = 1,
    Play = 2,
    RoundEnd = 3,
    MatchEnd = 4,
}

struct Sfx {
    bump: Sound,
    dash: Sound,
    splash: Sound,
    crack: Sound,
    brk: Sound,
    join: Sound,
    puck: Sound,
    tick: Sound,
    go: Sound,
    round: Sound,
    matchw: Sound,
    music: Sound,
    lobby: Sound,
}

fn sfx(s: &Sound, volume: f32) {
    play_sound(s, PlaySoundParams { looped: false, volume });
}

struct Game {
    mode: Mode,
    mode_t: f32,
    human: [bool; SEATS],
    joined_t: [f32; SEATS],
    skill: usize,
    wins: [u32; SEATS],
    round: u32,
    bs: [Bumper; SEATS],
    ais: [Ai; SEATS],
    floe: Floe,
    chunks: Vec<Chunk>,
    parts: Vec<Part>,
    ripples: Vec<Ripple>,
    puck: Option<Vec2>,
    puck_in: f32,
    end_in: f32,
    round_winner: i32,
    match_winner: i32,
    hits: i32,
    falls: i32,
    out_order: Vec<usize>,
    music: u8,
    frames: u64,
    waves: Vec<Vec3>,
}

impl Game {
    fn new() -> Game {
        let waves = (0..70)
            .map(|_| vec3(rand::gen_range(0.0, W), rand::gen_range(0.0, H), rand::gen_range(0.0, TAU)))
            .collect();
        Game {
            mode: Mode::Lobby,
            mode_t: 0.0,
            human: [false; SEATS],
            joined_t: [0.0; SEATS],
            skill: 0,
            wins: [0; SEATS],
            round: 0,
            bs: [Bumper::default(); SEATS],
            ais: [Ai::default(); SEATS],
            floe: Floe::new(),
            chunks: Vec::new(),
            parts: Vec::new(),
            ripples: Vec::new(),
            puck: None,
            puck_in: 6.0,
            end_in: -1.0,
            round_winner: -1,
            match_winner: -1,
            hits: 0,
            falls: 0,
            out_order: Vec::new(),
            music: 0,
            frames: 0,
            waves,
        }
    }

    fn set_mode(&mut self, m: Mode) {
        self.mode = m;
        self.mode_t = 0.0;
    }

    fn start_match(&mut self) {
        rand::srand(self.frames.wrapping_mul(2654435761) ^ 0x5eed);
        self.wins = [0; SEATS];
        self.round = 0;
        self.match_winner = -1;
        self.hits = 0;
        self.falls = 0;
        self.start_round();
    }

    fn start_round(&mut self) {
        self.round += 1;
        self.floe = Floe::new();
        self.chunks.clear();
        self.ripples.clear();
        self.puck = None;
        self.puck_in = rand::gen_range(5.0, 8.0);
        self.end_in = -1.0;
        self.round_winner = -1;
        self.out_order.clear();
        for i in 0..SEATS {
            let a = (-135.0 + 90.0 * i as f32).to_radians();
            self.bs[i] = Bumper {
                pos: C + dir(a) * 125.0,
                alive: true,
                face: a + std::f32::consts::PI,
                ..Default::default()
            };
            self.ais[i] = Ai { think: rand::gen_range(0.2, 0.8), target: (i + 1) % SEATS, ..Default::default() };
        }
        self.set_mode(Mode::Countdown);
    }

    fn splash(&mut self, at: Vec2, big: f32) {
        for _ in 0..(28.0 * big) as usize {
            let a = rand::gen_range(0.0, TAU);
            let s = rand::gen_range(30.0, 150.0) * big;
            let life = rand::gen_range(0.5, 0.95);
            self.parts.push(Part {
                pos: at,
                z: 0.0,
                vel: dir(a) * s,
                vz: rand::gen_range(120.0, 300.0) * big,
                life,
                max: life,
                size: rand::gen_range(2.0, 5.0),
                color: if rand::gen_range(0.0, 1.0) < 0.5 {
                    Color::from_rgba(220, 240, 255, 255)
                } else {
                    Color::from_rgba(120, 190, 235, 255)
                },
            });
        }
        self.ripples.push(Ripple { pos: at, t: 0.0, max: 1.4 });
        self.ripples.push(Ripple { pos: at, t: -0.25, max: 1.4 });
    }

    fn spray(&mut self, at: Vec2, vel: Vec2, n: usize) {
        for _ in 0..n {
            let a = rand::gen_range(0.0, TAU);
            let life = rand::gen_range(0.25, 0.5);
            self.parts.push(Part {
                pos: at + dir(a) * rand::gen_range(0.0, 8.0),
                z: 0.0,
                vel: -vel * rand::gen_range(0.05, 0.25) + dir(a) * rand::gen_range(10.0, 50.0),
                vz: rand::gen_range(20.0, 90.0),
                life,
                max: life,
                size: rand::gen_range(1.5, 3.0),
                color: Color::from_rgba(245, 252, 255, 255),
            });
        }
    }

    fn sparks(&mut self, at: Vec2, n: usize) {
        for _ in 0..n {
            let a = rand::gen_range(0.0, TAU);
            let life = rand::gen_range(0.2, 0.4);
            self.parts.push(Part {
                pos: at,
                z: 6.0,
                vel: dir(a) * rand::gen_range(80.0, 220.0),
                vz: rand::gen_range(0.0, 60.0),
                life,
                max: life,
                size: rand::gen_range(2.0, 3.5),
                color: Color::from_rgba(255, 246, 210, 255),
            });
        }
    }

    fn alive(&self) -> usize {
        self.bs.iter().filter(|b| b.alive).count()
    }
}

