//! Bumper Floe: a 1 to 4 player party game on a breaking ice floe.
//!
//! Round bumpers slide on the ice with real momentum. Hold A to charge a
//! dash, release it to shove whoever is in the way; B digs in to brake. The
//! floe cracks and loses chunks while the round runs, then melts, so every
//! round ends. The last bumper on the ice wins the round; the first to three
//! rounds wins the match.
//!
//! Every pad is its own seat (P1 to P4): press A on the lobby screen to join,
//! Start to begin. Seats nobody joins get CPU bumpers, so one player can play
//! a whole match alone. A pad that is connected but never pressed does not
//! join. The keyboard drives P1 as a fallback (arrows, Space, Shift, Enter).
//!
//! Sounds and music are WAV assets generated by gen-assets.mjs.

use macroquad::audio::{load_sound, play_sound, stop_sound, PlaySoundParams, Sound};
use macroquad::prelude::*;
use std::f32::consts::TAU;
use wasmcart_macroquad as wc;

const W: f32 = 960.0;
const H: f32 = 540.0;
/// Floe centre.
const C: Vec2 = Vec2::new(480.0, 300.0);
/// Starting floe radius.
const FLOE_R: f32 = 222.0;
/// Edge vertices around the floe.
const N: usize = 48;
/// Bumper radius.
const BR: f32 = 23.0;
const WINS_TO_MATCH: u32 = 3;
/// The floe never melts below this: room for one bumper, never two, so a
/// round always ends with a single winner.
const CORE_R: f32 = 18.0;
const SEATS: usize = 4;

const MAX_SPEED: f32 = 285.0;
const ACCEL: f32 = 820.0;
const DRAG: f32 = 1.3;
/// Extra drag while a dash runs, so a dash is a burst, not a launch.
const DASH_DRAG: f32 = 3.0;
const BRAKE_DRAG: f32 = 4.5;
const CHARGE_TIME: f32 = 0.7;
const DASH_MIN: f32 = 280.0;
const DASH_MAX: f32 = 560.0;

fn window_conf() -> Conf {
    Conf {
        window_title: "Bumper Floe".to_owned(),
        window_width: W as i32,
        window_height: H as i32,
        ..Default::default()
    }
}

const COLOR_NAMES: [&str; SEATS] = ["RED", "BLUE", "YELLOW", "GREEN"];

fn seat_color(i: usize) -> Color {
    match i {
        0 => Color::from_rgba(240, 92, 82, 255),
        1 => Color::from_rgba(72, 142, 240, 255),
        2 => Color::from_rgba(244, 196, 52, 255),
        _ => Color::from_rgba(86, 196, 108, 255),
    }
}

fn shade(c: Color, k: f32) -> Color {
    Color::new(c.r * k, c.g * k, c.b * k, c.a)
}

fn with_alpha(c: Color, a: f32) -> Color {
    Color::new(c.r, c.g, c.b, a)
}

fn dir(a: f32) -> Vec2 {
    vec2(a.cos(), a.sin())
}

// ─── input ──────────────────────────────────────────────────────────────

/// One seat's controls for one frame, from a pad, the keyboard or the AI.
#[derive(Clone, Copy, Default)]
struct Ctl {
    mv: Vec2,
    a: bool,
    a_pressed: bool,
    b: bool,
    b_pressed: bool,
    start_pressed: bool,
    left_pressed: bool,
    right_pressed: bool,
}

/// Read pad `i` (and, for seat 0, the keyboard fallback).
fn read_pad(i: usize, prev: &mut [u32; SEATS]) -> Ctl {
    let p = wc::pad(i);
    let mut buttons = if p.connected != 0 { p.buttons } else { 0 };
    let mut mv = Vec2::ZERO;
    if p.connected != 0 {
        let s = vec2(p.left_x as f32 / 32767.0, p.left_y as f32 / 32767.0);
        let len = s.length();
        if len > 0.22 {
            mv = s / len * ((len - 0.22) / 0.78).min(1.0);
        }
    }
    if i == 0 {
        let keys = [
            (KeyCode::Up, wc::WC_BTN_UP),
            (KeyCode::Down, wc::WC_BTN_DOWN),
            (KeyCode::Left, wc::WC_BTN_LEFT),
            (KeyCode::Right, wc::WC_BTN_RIGHT),
            (KeyCode::Space, wc::WC_BTN_A),
            (KeyCode::LeftShift, wc::WC_BTN_B),
            (KeyCode::X, wc::WC_BTN_B),
            (KeyCode::Enter, wc::WC_BTN_START),
        ];
        for (k, b) in keys {
            if is_key_down(k) {
                buttons |= b;
            }
        }
    }
    let mut d = Vec2::ZERO;
    if buttons & wc::WC_BTN_LEFT != 0 {
        d.x -= 1.0;
    }
    if buttons & wc::WC_BTN_RIGHT != 0 {
        d.x += 1.0;
    }
    if buttons & wc::WC_BTN_UP != 0 {
        d.y -= 1.0;
    }
    if buttons & wc::WC_BTN_DOWN != 0 {
        d.y += 1.0;
    }
    if d != Vec2::ZERO {
        mv = d.normalize();
    }
    let pressed = buttons & !prev[i];
    prev[i] = buttons;
    Ctl {
        mv,
        a: buttons & wc::WC_BTN_A != 0,
        a_pressed: pressed & wc::WC_BTN_A != 0,
        b: buttons & wc::WC_BTN_B != 0,
        b_pressed: pressed & wc::WC_BTN_B != 0,
        start_pressed: pressed & wc::WC_BTN_START != 0,
        left_pressed: pressed & wc::WC_BTN_LEFT != 0,
        right_pressed: pressed & wc::WC_BTN_RIGHT != 0,
    }
}

// ─── the floe ───────────────────────────────────────────────────────────

/// A strip of the edge that is cracking and will break off.
struct Crack {
    start: usize,
    width: usize,
    depth: f32,
    t: f32,
    total: f32,
    /// Jitter of the crack line per vertex.
    wobble: Vec<f32>,
}

/// A broken-off piece drifting away and sinking.
struct Chunk {
    quads: Vec<[Vec2; 4]>,
    center: Vec2,
    vel: Vec2,
    rot: f32,
    spin: f32,
    life: f32,
}

struct Floe {
    r: [f32; N],
    jag: [f32; N],
    crack: Option<Crack>,
    next_break: f32,
    time: f32,
}

impl Floe {
    fn new() -> Floe {
        let mut jag = [0.0; N];
        for j in jag.iter_mut() {
            *j = rand::gen_range(-3.5, 3.5);
        }
        Floe { r: [FLOE_R; N], jag, crack: None, next_break: 2.0, time: 0.0 }
    }

    /// Edge radius toward angle `a`.
    fn edge(&self, a: f32) -> f32 {
        let f = a.rem_euclid(TAU) / TAU * N as f32;
        let i = (f as usize) % N;
        let t = f.fract();
        self.r[i] * (1.0 - t) + self.r[(i + 1) % N] * t
    }

    /// How far `p` is inside the edge (negative: in the water).
    fn margin(&self, p: Vec2) -> f32 {
        let d = p - C;
        self.edge(d.y.atan2(d.x)) - d.length()
    }

    fn mean(&self) -> f32 {
        self.r.iter().sum::<f32>() / N as f32
    }

    fn vertex(&self, i: usize, r: f32) -> Vec2 {
        C + dir(i as f32 / N as f32 * TAU) * r
    }

    fn taper(width: usize, k: usize) -> f32 {
        // Full depth in the middle of the strip, shallower at its ends.
        let x = (k as f32 + 0.5) / (width as f32 + 1.0) * std::f32::consts::PI;
        x.sin().powf(0.6)
    }

    /// Advance cracking, breaking and melting. Returns (crack started, broke).
    fn update(&mut self, dt: f32, chunks: &mut Vec<Chunk>) -> (bool, bool) {
        self.time += dt;
        let mut started = false;
        let mut broke = false;
        if self.crack.is_none() {
            self.next_break -= dt;
            if self.next_break <= 0.0 {
                let maxr = self.r.iter().cloned().fold(0.0, f32::max);
                let cands: Vec<usize> = (0..N).filter(|&i| self.r[i] >= maxr * 0.85).collect();
                let start = cands[rand::gen_range(0, cands.len())];
                let width = rand::gen_range(4, 8);
                let depth = rand::gen_range(34.0, 58.0);
                let total = 1.8;
                let wobble = (0..=width + 1).map(|_| rand::gen_range(-5.0, 5.0)).collect();
                self.crack = Some(Crack { start, width, depth, t: total, total, wobble });
                started = true;
            }
        }
        if let Some(c) = &mut self.crack {
            c.t -= dt;
            if c.t <= 0.0 {
                let (start, width, depth) = (c.start, c.width, c.depth);
                self.crack = None;
                let mut quads = Vec::new();
                let mut sum = Vec2::ZERO;
                for k in 0..width {
                    let i0 = (start + k) % N;
                    let i1 = (start + k + 1) % N;
                    let o0 = self.r[i0];
                    let o1 = self.r[i1];
                    let n0 = (o0 - depth * Floe::taper(width, k)).max(CORE_R.min(o0));
                    let n1 = (o1 - depth * Floe::taper(width, k + 1)).max(CORE_R.min(o1));
                    let q = [self.vertex(i0, n0), self.vertex(i0, o0), self.vertex(i1, o1), self.vertex(i1, n1)];
                    sum += (q[0] + q[1] + q[2] + q[3]) / 4.0;
                    quads.push(q);
                }
                for k in 0..=width {
                    let i = (start + k) % N;
                    let cut = depth * Floe::taper(width, k);
                    // The ends of the strip share a vertex with the old edge.
                    if k > 0 && k < width {
                        self.r[i] = (self.r[i] - cut).max(CORE_R.min(self.r[i]));
                    }
                }
                let center = sum / width as f32;
                let rel: Vec<[Vec2; 4]> =
                    quads.iter().map(|q| [q[0] - center, q[1] - center, q[2] - center, q[3] - center]).collect();
                chunks.push(Chunk {
                    quads: rel,
                    center,
                    vel: (center - C).normalize_or_zero() * rand::gen_range(30.0, 50.0),
                    rot: 0.0,
                    spin: rand::gen_range(-0.4, 0.4),
                    life: 3.2,
                });
                self.next_break = (2.6 - self.time * 0.05).max(1.3) + rand::gen_range(0.0, 0.8);
                broke = true;
            }
        }
        // After a while the whole floe melts, so every round ends.
        if self.time > 14.0 {
            let rate = 5.0 + (self.time - 14.0) * 0.6;
            for r in self.r.iter_mut() {
                *r = (*r - rate * dt).max(CORE_R.min(*r));
            }
        }
        (started, broke)
    }
}

