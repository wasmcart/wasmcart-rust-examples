#[derive(Clone, Copy, Default)]
struct Bumper {
    pos: Vec2,
    vel: Vec2,
    alive: bool,
    /// Seconds left of the sinking animation after a fall.
    sink: f32,
    charging: bool,
    charge: f32,
    cooldown: f32,
    dash_t: f32,
    heavy: bool,
    heavy_dash: bool,
    squash: f32,
    squash_ang: f32,
    face: f32,
    hop: f32,
    spray: f32,
}

impl Bumper {
    fn mass(&self) -> f32 {
        if self.dash_t > 0.0 {
            if self.heavy_dash {
                3.0
            } else {
                1.6
            }
        } else if self.charging {
            1.3
        } else {
            1.0
        }
    }
}

