#[derive(Clone, Copy, Default)]
struct Ai {
    think: f32,
    target: usize,
    err: f32,
    holding: bool,
    goal: f32,
    wander: Vec2,
}

fn ai_control(seat: usize, ai: &mut Ai, bs: &[Bumper; SEATS], floe: &Floe, puck: Option<Vec2>, sk: &Skill, dt: f32) -> Ctl {
    let me = bs[seat];
    let mut ctl = Ctl::default();
    if !me.alive {
        return ctl;
    }
    ai.think -= dt;
    let fresh = ai.think <= 0.0;
    if fresh {
        ai.think = sk.think * rand::gen_range(0.7, 1.3);
        // Usually the nearest rival, sometimes anyone.
        let mut best = None;
        let mut bd = f32::MAX;
        for (j, o) in bs.iter().enumerate() {
            if j != seat && o.alive {
                let d = o.pos.distance(me.pos) * rand::gen_range(0.7, 1.3);
                if d < bd {
                    bd = d;
                    best = Some(j);
                }
            }
        }
        if let Some(b) = best {
            ai.target = b;
        }
        ai.err = rand::gen_range(-sk.aim_err, sk.aim_err);
        ai.wander = dir(rand::gen_range(0.0, TAU)) * rand::gen_range(0.0, 60.0);
    }
    // Where it would stop if it braked now (seen short by weaker CPUs).
    let pred = me.pos + me.vel / BRAKE_DRAG.max(DRAG) * sk.look + me.vel * 0.12;
    let danger = floe.margin(pred) < sk.safety || floe.margin(me.pos) < sk.safety * 0.6;
    let to_c = (C + ai.wander * 0.3 - me.pos).normalize_or_zero();
    let tgt = bs[ai.target];
    let mut want = to_c;
    if danger {
        if sk.brakes && me.vel.dot(me.pos - C) > 0.0 {
            ctl.b = true;
        }
        // A good bumper dashes back to safety.
        if me.charging && sk.brakes {
            ai.holding = false;
        }
    } else if tgt.alive && ai.target != seat {
        let to = tgt.pos - me.pos;
        let dist = to.length();
        let base = to.y.atan2(to.x) + ai.err;
        want = dir(base);
        // Grab a nearby puck first.
        if let Some(pk) = puck {
            if pk.distance(me.pos) < dist * 0.8 && floe.margin(pk) > sk.safety {
                want = (pk - me.pos).normalize_or_zero();
            }
        }
        if !me.charging && me.cooldown <= 0.0 && dist < sk.range && fresh && rand::gen_range(0.0, 1.0) < sk.dash_chance {
            ai.holding = true;
            ai.goal = rand::gen_range(sk.charge.0, sk.charge.1);
        }
        if me.charging && me.charge >= ai.goal {
            ai.holding = false;
            want = dir(base);
        }
    } else {
        want = (C + ai.wander - me.pos).normalize_or_zero();
    }
    ctl.mv = want * sk.accel;
    ctl.a = ai.holding;
    ctl.a_pressed = ai.holding && !me.charging;
    ctl
}

